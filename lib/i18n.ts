const MONTHS: Record<Locale, string[]> = {
  fr: ["janv.", "févr.", "mars", "avr.", "mai", "juin", "juil.", "août", "sept.", "oct.", "nov.", "déc."],
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
};
export function fmtDate(iso: string, l: Locale, long = false) {
  const [y, m, d] = iso.split("-").map(Number);
  if (l === "en") return long ? `${MONTHS.en[m - 1]} ${d}, ${y}` : `${MONTHS.en[m - 1]} ${d}`;
  const day = d === 1 ? "1er" : String(d);
  return long ? `${day} ${MONTHS.fr[m - 1]} ${y}` : `${day} ${MONTHS.fr[m - 1]}`;
}
export function monthWord(iso: string, l: Locale) {
  return MONTHS[l][Number(iso.split("-")[1]) - 1];
}
